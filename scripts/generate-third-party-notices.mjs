#!/usr/bin/env node
/**
 * Generates THIRD-PARTY-NOTICES.txt (FER-554): the license notices for every third-party component
 * that ships with Ferrum, so the installer carries the texts the licenses require.
 *
 *   node scripts/generate-third-party-notices.mjs           write THIRD-PARTY-NOTICES.txt
 *   node scripts/generate-third-party-notices.mjs --check   fail when the file is out of date (CI)
 *
 * Sources:
 *   - Rust: `cargo metadata` for the Windows target (src-tauri/Cargo.lock, --locked), normal
 *     dependencies only, license files read from the crate sources in the cargo registry.
 *   - npm: package-lock.json, packages that reach the frontend bundle, license files read from
 *     node_modules (run `npm ci` first).
 *   - licenses/special-notices.txt: UnRAR, SQLite and the WinRAR note, kept verbatim.
 * It fails (non-zero, with the list) when a component has no license file, no declared license, or a
 * license outside the allowlist in scripts/lib/third-party-notices.mjs.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  collectNpmComponents,
  collectRustComponents,
  normalizeText,
  readLicenseFiles,
  renderNotices,
  validateComponents,
  withSynthesizedLicenseFiles,
} from './lib/third-party-notices.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = join(ROOT, 'THIRD-PARTY-NOTICES.txt');
const TARGET = 'x86_64-pc-windows-msvc';
/** Build-time npm packages whose runtime is compiled into the frontend bundle. */
const EXTRA_BUNDLED_NPM = ['svelte'];

const HEADER = `Ferrum third-party notices

Ferrum is licensed under MIT OR Apache-2.0 (see LICENSE-MIT and LICENSE-APACHE).
It includes the third-party software listed below. This file is generated by
scripts/generate-third-party-notices.mjs; do not edit it by hand.

Components under MPL-2.0 are used unmodified; their source code is available at
the repository URL listed with each component.`;

function rustComponents() {
  const out = execFileSync(
    'cargo',
    ['metadata', '--format-version', '1', '--locked', '--filter-platform', TARGET],
    {
      cwd: join(ROOT, 'src-tauri'),
      encoding: 'utf8',
      maxBuffer: 1 << 30,
      stdio: ['ignore', 'pipe', 'inherit'],
    },
  );
  return collectRustComponents(JSON.parse(out));
}

function npmComponents() {
  const lock = JSON.parse(readFileSync(join(ROOT, 'package-lock.json'), 'utf8'));
  const readPackageDir = (key) => {
    const dir = join(ROOT, key);
    if (!existsSync(dir)) throw new Error(`${key} is not installed; run "npm ci" first`);
    const manifestPath = join(dir, 'package.json');
    return {
      manifest: existsSync(manifestPath) ? JSON.parse(readFileSync(manifestPath, 'utf8')) : {},
      files: readLicenseFiles(dir),
    };
  };
  return collectNpmComponents(lock, readPackageDir, EXTRA_BUNDLED_NPM);
}

function loadTemplates() {
  const dir = join(ROOT, 'scripts', 'license-templates');
  return Object.fromEntries(
    readdirSync(dir)
      .filter((f) => f.endsWith('.txt'))
      .map((f) => [f.slice(0, -4), readFileSync(join(dir, f), 'utf8')]),
  );
}

function main() {
  const check = process.argv.includes('--check');
  const components = withSynthesizedLicenseFiles(
    [...rustComponents(), ...npmComponents()],
    loadTemplates(),
  );

  const problems = validateComponents(components);
  if (problems.length) {
    console.error(`Third-party notice generation failed (${problems.length} problem(s)):`);
    for (const p of problems.sort()) console.error(`  - ${p}`);
    process.exit(1);
  }

  const special = readFileSync(join(ROOT, 'licenses', 'special-notices.txt'), 'utf8');
  const text = renderNotices({ components, header: HEADER, special: normalizeText(special) });

  if (check) {
    const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8').replace(/\r\n/g, '\n') : null;
    if (current !== text) {
      console.error(
        'THIRD-PARTY-NOTICES.txt is out of date. Run "node scripts/generate-third-party-notices.mjs" and commit the result.',
      );
      process.exit(1);
    }
    console.log(`THIRD-PARTY-NOTICES.txt is up to date (${components.length} components).`);
    return;
  }
  writeFileSync(OUTPUT, text);
  console.log(`Wrote THIRD-PARTY-NOTICES.txt (${components.length} components).`);
}

main();
